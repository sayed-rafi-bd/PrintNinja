import { mkdtempSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { readFileSync } from "node:fs";
import { dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { DatabaseSync } from "node:sqlite";
import { afterAll, beforeAll, describe, expect, it } from "vitest";
import { importV1 } from "../../scripts/import-v1.js";
import { buildApp } from "../../src/app.js";
import { testConfig } from "../helpers.js";
import { realDeps, startTestDatabase, truncateAll, type TestStack } from "./db.js";

// E9 cutover rehearsal (REFACTORING.md section 7/11): a copy of a real
// Rust database — generated by running server-legacy, registering twice
// (real scrypt passwords), publishing one template, keeping one private
// and saving one — imports cleanly, and afterwards an old password logs
// in (rehashing to argon2id), an old session token still authenticates,
// templates list under their original ids (remote_id stays valid), and
// the saved list and manifest survive. The fixture's session expiry is
// extended after import: expiry is orthogonal to token-hash compat, and
// the baked-in dates would otherwise rot the test.

const here = dirname(fileURLToPath(import.meta.url));
const FIXTURE_SQL = readFileSync(join(here, "..", "fixtures", "v1-import.sql"), "utf8");
// Rafi's token, captured from the real legacy register response. Test-only.
const RAFI_TOKEN = "Zj49am16PVFxLnDb3L-xrxDseV8JDr_ncKh1NDbWdFI";
const RAFI_ID = "bf75a279-1a34-4207-b0a1-4303a4c8bc3d";
const AIKO_TOKEN = "uAZ7EEtTKFMEJ76d7isgmtTwvDlCTMr-D6Qaoxi3iTI";

let stack: TestStack;

beforeAll(async () => {
	stack = await startTestDatabase();
}, 180_000);

afterAll(async () => {
	await stack?.stop();
});

function fixtureDb(): string {
	const dir = mkdtempSync(join(tmpdir(), "v1-import-"));
	const path = join(dir, "v1.db");
	const db = new DatabaseSync(path);
	db.exec(FIXTURE_SQL);
	db.close();
	return path;
}

describe("E9 import rehearsal", () => {
	it("dry-runs with row counts and writes nothing", async () => {
		await truncateAll(stack.db);
		const report = await importV1({ sqlitePath: fixtureDb(), db: stack.db, dryRun: true });

		expect(report.dryRun).toBe(true);
		expect(report.counts).toMatchObject({
			users: 2,
			sessions: 2,
			templates: 2,
			published: 1,
			saved: 1,
			userSyncs: 2,
		});
		expect(await stack.db.user.count()).toBe(0);
	});

	it("imports everything and the old credentials keep working", async () => {
		await truncateAll(stack.db);
		const report = await importV1({ sqlitePath: fixtureDb(), db: stack.db, dryRun: false });

	 expect(report.dryRun).toBe(false);
		expect(await stack.db.user.count()).toBe(2);
		expect(await stack.db.template.count()).toBe(2);
		expect(await stack.db.templateVersion.count()).toBe(2);
		expect(await stack.db.userSync.count()).toBe(2);

		// The fixture's baked-in expiry would rot the test; expiry is
		// orthogonal to what the rehearsal proves (the token hash).
		await stack.db.session.updateMany({ data: { expiresAt: new Date("2126-01-01T00:00:00Z") } });

		const app = await buildApp({ config: testConfig(), deps: realDeps(stack.db) });
		try {
			// An old session token still authenticates, same user id.
			const me = await app.inject({ method: "GET", url: "/v2/auth/me", headers: { authorization: `Bearer ${RAFI_TOKEN}` } });
			expect(me.statusCode).toBe(200);
			expect((me.json() as { id: string }).id).toBe(RAFI_ID);

			// An old scrypt password logs in — and is rehashed to argon2id.
			const login = await app.inject({
				method: "POST",
				url: "/v2/auth/login",
				payload: { handle: "Rafi", password: "correct horse battery" },
			});
			expect(login.statusCode).toBe(200);
			const stored = await stack.db.user.findUniqueOrThrow({ where: { id: RAFI_ID } });
			expect(stored.passwordHash.startsWith("$argon2id$")).toBe(true);

			// Templates list under their original ids (remote_id compatible).
		 const community = await app.inject({ method: "GET", url: "/v2/community/templates?page_size=100" });
			const ids = ((community.json() as { items: { id: string; name: string }[] }).items).map((t) => t.id);
			expect(ids).toContain("f4aebf12-9dd4-4532-8f1f-4f6e6851f8ad");

			// The private template stays private; the owner reads it.
			const privates = await stack.db.template.findMany({ where: { publishedAt: null } });
			expect(privates).toHaveLength(1);
			const anon = await app.inject({ method: "GET", url: `/v2/templates/${privates[0]?.id}` });
			expect(anon.statusCode).toBe(404);

			// The saved list and manifest survived the move.
			const saved = await app.inject({ method: "GET", url: "/v2/saved?page_size=100", headers: { authorization: `Bearer ${AIKO_TOKEN}` } });
			expect((saved.json() as { items: { id: string }[] }).items.map((t) => t.id)).toEqual([
				"f4aebf12-9dd4-4532-8f1f-4f6e6851f8ad",
			]);
			const manifest = await app.inject({ method: "GET", url: "/v2/saved/manifest", headers: { authorization: `Bearer ${AIKO_TOKEN}` } });
			expect((manifest.json() as { items: unknown[] }).items).toHaveLength(1);
		} finally {
			await app.close();
		}
	}, 120_000);
});
